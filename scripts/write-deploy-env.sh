#!/usr/bin/env bash
# Write /opt/skillmark/.env for production compose (URL-encodes DB password for PostgREST).
set -euo pipefail

: "${POSTGRES_USER:?}"
: "${POSTGRES_PASSWORD:?}"
: "${POSTGRES_DB:?}"
: "${AUTH_SECRET:?}"
: "${NEXT_PUBLIC_APP_URL:?}"
: "${POSTGREST_URL:?}"
: "${STORAGE_DIR:?}"

# Keep the previous .env value when a deploy secret is empty (prevents wiping LiveKit / STT / OAuth keys).
keep() {
  local key="$1" new="${2:-}"
  if [ -n "$new" ]; then
    printf '%s' "$new"
    return
  fi
  if [ -f .env ]; then
    local old
    old="$(grep -E "^${key}=" .env | head -1 | cut -d= -f2- || true)"
    printf '%s' "$old"
  fi
}

PGRST_DB_URI="$(
  POSTGRES_USER="$POSTGRES_USER" \
  POSTGRES_PASSWORD="$POSTGRES_PASSWORD" \
  POSTGRES_DB="$POSTGRES_DB" \
  python3 -c 'import os,urllib.parse as u; print("postgres://%s:%s@db:5432/%s" % (os.environ["POSTGRES_USER"], u.quote(os.environ["POSTGRES_PASSWORD"], safe=""), os.environ["POSTGRES_DB"]))'
)"

GEMINI_API_KEY="$(keep GEMINI_API_KEY "${GEMINI_API_KEY:-}")"
CODE_RUNNER_API_KEY="$(keep CODE_RUNNER_API_KEY "${CODE_RUNNER_API_KEY:-}")"
OPENAI_API_KEY="$(keep OPENAI_API_KEY "${OPENAI_API_KEY:-}")"
DOUBAO_APP_ID="$(keep DOUBAO_APP_ID "${DOUBAO_APP_ID:-}")"
DOUBAO_ACCESS_TOKEN="$(keep DOUBAO_ACCESS_TOKEN "${DOUBAO_ACCESS_TOKEN:-}")"
AZURE_OPENAI_ENDPOINT="$(keep AZURE_OPENAI_ENDPOINT "${AZURE_OPENAI_ENDPOINT:-}")"
AZURE_OPENAI_API_KEY="$(keep AZURE_OPENAI_API_KEY "${AZURE_OPENAI_API_KEY:-}")"
GRAFANA_URL="$(keep GRAFANA_URL "${GRAFANA_URL:-}")"
GRAFANA_SERVICE_ACCOUNT_TOKEN="$(keep GRAFANA_SERVICE_ACCOUNT_TOKEN "${GRAFANA_SERVICE_ACCOUNT_TOKEN:-}")"
UPTIMEROBOT_API_KEY="$(keep UPTIMEROBOT_API_KEY "${UPTIMEROBOT_API_KEY:-}")"
LIVEKIT_URL="$(keep LIVEKIT_URL "${LIVEKIT_URL:-}")"
LIVEKIT_API_KEY="$(keep LIVEKIT_API_KEY "${LIVEKIT_API_KEY:-}")"
LIVEKIT_API_SECRET="$(keep LIVEKIT_API_SECRET "${LIVEKIT_API_SECRET:-}")"
ROUND2_AGENT_SECRET="$(keep ROUND2_AGENT_SECRET "${ROUND2_AGENT_SECRET:-}")"
ROUND2_STT_API_KEY="$(keep ROUND2_STT_API_KEY "${ROUND2_STT_API_KEY:-}")"
ROUND2_STT_BASE_URL="$(keep ROUND2_STT_BASE_URL "${ROUND2_STT_BASE_URL:-}")"
ROUND2_STT_MODEL="$(keep ROUND2_STT_MODEL "${ROUND2_STT_MODEL:-}")"
GOOGLE_CLIENT_ID="$(keep GOOGLE_CLIENT_ID "${GOOGLE_CLIENT_ID:-}")"
GOOGLE_CLIENT_SECRET="$(keep GOOGLE_CLIENT_SECRET "${GOOGLE_CLIENT_SECRET:-}")"
LANGFUSE_PUBLIC_KEY="$(keep LANGFUSE_PUBLIC_KEY "${LANGFUSE_PUBLIC_KEY:-}")"
LANGFUSE_SECRET_KEY="$(keep LANGFUSE_SECRET_KEY "${LANGFUSE_SECRET_KEY:-}")"
LANGFUSE_BASE_URL="$(keep LANGFUSE_BASE_URL "${LANGFUSE_BASE_URL:-}")"
LANGFUSE_PUBLIC_URL="$(keep LANGFUSE_PUBLIC_URL "${LANGFUSE_PUBLIC_URL:-}")"
LANGFUSE_PROJECT_ID="$(keep LANGFUSE_PROJECT_ID "${LANGFUSE_PROJECT_ID:-}")"
LANGFUSE_SERVER_SECRET="$(keep LANGFUSE_SERVER_SECRET "${LANGFUSE_SERVER_SECRET:-}")"
LANGFUSE_DOMAIN="$(keep LANGFUSE_DOMAIN "${LANGFUSE_DOMAIN:-}")"
LANGFUSE_INIT_USER_EMAIL="$(keep LANGFUSE_INIT_USER_EMAIL "${LANGFUSE_INIT_USER_EMAIL:-}")"
LANGFUSE_INIT_USER_PASSWORD="$(keep LANGFUSE_INIT_USER_PASSWORD "${LANGFUSE_INIT_USER_PASSWORD:-}")"

# Self-hosted Langfuse: one LANGFUSE_SERVER_SECRET → all internal Langfuse secrets (stable per label).
COMPOSE_PROFILES=""
LANGFUSE_BLOCK=""
if [ -n "${LANGFUSE_SERVER_SECRET:-}" ]; then
  : "${LANGFUSE_DOMAIN:?LANGFUSE_DOMAIN required with LANGFUSE_SERVER_SECRET}"
  derive() { printf '%s:%s' "$LANGFUSE_SERVER_SECRET" "$1" | sha256sum | cut -c1-64; }
  COMPOSE_PROFILES="langfuse"
  LANGFUSE_BASE_URL="${LANGFUSE_BASE_URL:-http://langfuse-web:3000}"
  LANGFUSE_PUBLIC_URL="${LANGFUSE_PUBLIC_URL:-https://${LANGFUSE_DOMAIN}}"
  LANGFUSE_PROJECT_ID="${LANGFUSE_PROJECT_ID:-skillmark}"
  LANGFUSE_BLOCK="LANGFUSE_DOMAIN=${LANGFUSE_DOMAIN}
LANGFUSE_SALT=$(derive salt)
LANGFUSE_ENCRYPTION_KEY=$(derive encryption)
LANGFUSE_NEXTAUTH_SECRET=$(derive nextauth)
LANGFUSE_DB_PASSWORD=$(derive db)
LANGFUSE_CLICKHOUSE_PASSWORD=$(derive clickhouse)
LANGFUSE_MINIO_PASSWORD=$(derive minio)
LANGFUSE_REDIS_PASSWORD=$(derive redis)
LANGFUSE_INIT_USER_EMAIL=${LANGFUSE_INIT_USER_EMAIL:-}
LANGFUSE_INIT_USER_PASSWORD=${LANGFUSE_INIT_USER_PASSWORD:-}"
fi

umask 077
cat > .env <<EOF
COMPOSE_PROFILES=${COMPOSE_PROFILES}
POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=${POSTGRES_DB}
POSTGRES_PORT=5433
POSTGREST_PORT=3001
POSTGREST_URL=${POSTGREST_URL}
PGRST_DB_URI=${PGRST_DB_URI}
AUTH_SECRET=${AUTH_SECRET}
NEXT_PUBLIC_APP_URL=${NEXT_PUBLIC_APP_URL}
STORAGE_DIR=${STORAGE_DIR}
CRON_SECRET=${CRON_SECRET:-}
SITE_ADDRESS=${SITE_ADDRESS:-:80}
VOICE_RELAY_PROVIDER=${VOICE_RELAY_PROVIDER:-auto}
GEMINI_API_KEY=${GEMINI_API_KEY}
CODE_RUNNER_API_KEY=${CODE_RUNNER_API_KEY}
OPENAI_API_KEY=${OPENAI_API_KEY}
DOUBAO_APP_ID=${DOUBAO_APP_ID}
DOUBAO_ACCESS_TOKEN=${DOUBAO_ACCESS_TOKEN}
AZURE_OPENAI_ENDPOINT=${AZURE_OPENAI_ENDPOINT}
AZURE_OPENAI_API_KEY=${AZURE_OPENAI_API_KEY}
GRAFANA_URL=${GRAFANA_URL}
GRAFANA_SERVICE_ACCOUNT_TOKEN=${GRAFANA_SERVICE_ACCOUNT_TOKEN}
GRAFANA_LOKI_DATASOURCE_UID=${GRAFANA_LOKI_DATASOURCE_UID:-grafanacloud-logs}
GRAFANA_LOG_INSTANCE=${GRAFANA_LOG_INSTANCE:-skillmark}
UPTIMEROBOT_API_KEY=${UPTIMEROBOT_API_KEY}
LIVEKIT_URL=${LIVEKIT_URL}
LIVEKIT_API_KEY=${LIVEKIT_API_KEY}
LIVEKIT_API_SECRET=${LIVEKIT_API_SECRET}
ROUND2_AGENT_SECRET=${ROUND2_AGENT_SECRET}
ROUND2_STT_API_KEY=${ROUND2_STT_API_KEY}
ROUND2_STT_BASE_URL=${ROUND2_STT_BASE_URL}
ROUND2_STT_MODEL=${ROUND2_STT_MODEL}
GOOGLE_CLIENT_ID=${GOOGLE_CLIENT_ID}
GOOGLE_CLIENT_SECRET=${GOOGLE_CLIENT_SECRET}
LANGFUSE_PUBLIC_KEY=${LANGFUSE_PUBLIC_KEY}
LANGFUSE_SECRET_KEY=${LANGFUSE_SECRET_KEY}
LANGFUSE_BASE_URL=${LANGFUSE_BASE_URL}
LANGFUSE_PUBLIC_URL=${LANGFUSE_PUBLIC_URL}
LANGFUSE_PROJECT_ID=${LANGFUSE_PROJECT_ID}
${LANGFUSE_BLOCK}
EOF

echo "wrote .env (PGRST_DB_URI encoded)"
