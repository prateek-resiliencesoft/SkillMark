#!/usr/bin/env bash
# Write /opt/skillmark/.env for production compose (URL-encodes DB password for PostgREST).
set -euo pipefail

: "${POSTGRES_USER:?}"
: "${POSTGRES_PASSWORD:?}"
: "${POSTGRES_DB:?}"
: "${AUTH_SECRET:?}"
: "${NEXT_PUBLIC_APP_URL:?}"
: "${POSTGREST_URL:?}"
: "${STORAGE_DIR:?}"

PGRST_DB_URI="$(
  POSTGRES_USER="$POSTGRES_USER" \
  POSTGRES_PASSWORD="$POSTGRES_PASSWORD" \
  POSTGRES_DB="$POSTGRES_DB" \
  python3 -c 'import os,urllib.parse as u; print("postgres://%s:%s@db:5432/%s" % (os.environ["POSTGRES_USER"], u.quote(os.environ["POSTGRES_PASSWORD"], safe=""), os.environ["POSTGRES_DB"]))'
)"

umask 077
cat > .env <<EOF
POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=${POSTGRES_DB}
POSTGRES_PORT=5433
POSTGREST_PORT=3001
POSTGREST_URL=${POSTGREST_URL}
PGRST_DB_URI=${PGRST_DB_URI}
AUTH_SECRET=${AUTH_SECRET}
NEXT_PUBLIC_APP_URL=${NEXT_PUBLIC_APP_URL}
STORAGE_DIR=${STORAGE_DIR}
S3_ENDPOINT=${S3_ENDPOINT:-}
S3_REGION=${S3_REGION:-}
S3_ACCESS_KEY_ID=${S3_ACCESS_KEY_ID:-}
S3_SECRET_ACCESS_KEY=${S3_SECRET_ACCESS_KEY:-}
S3_BUCKET=${S3_BUCKET:-}
CRON_SECRET=${CRON_SECRET:-}
SITE_ADDRESS=${SITE_ADDRESS:-:80}
VOICE_RELAY_PROVIDER=${VOICE_RELAY_PROVIDER:-auto}
GEMINI_API_KEY=${GEMINI_API_KEY:-}
OPENAI_API_KEY=${OPENAI_API_KEY:-}
DOUBAO_APP_ID=${DOUBAO_APP_ID:-}
DOUBAO_ACCESS_TOKEN=${DOUBAO_ACCESS_TOKEN:-}
AZURE_OPENAI_ENDPOINT=${AZURE_OPENAI_ENDPOINT:-}
AZURE_OPENAI_API_KEY=${AZURE_OPENAI_API_KEY:-}
EOF

echo "wrote .env (PGRST_DB_URI encoded)"
