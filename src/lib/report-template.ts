/* eslint-disable @typescript-eslint/no-explicit-any */
import { z } from "zod";

/** Sections a session report PDF can contain (order = default order). */
export const REPORT_SECTION_IDS = [
  "summary",
  "scores",
  "skills",
  "strengths",
  "questions",
  "transcript",
  "integrity",
  "errorLog",
  "candidate",
] as const;
export type ReportSectionId = (typeof REPORT_SECTION_IDS)[number];

export const REPORT_SECTION_LABELS: Record<ReportSectionId, string> = {
  summary: "Summary",
  scores: "Scores chart",
  skills: "Skills & competencies",
  strengths: "Strengths & concerns",
  questions: "Per-question details",
  transcript: "Transcript",
  integrity: "Integrity / anti-cheat",
  errorLog: "Error log",
  candidate: "Candidate details",
};

/** Logo is stored inline as a data URL; keep it small (≈ 200 KB of base64). */
export const MAX_LOGO_DATA_URL_LENGTH = 280_000;
const HEX = /^#[0-9a-fA-F]{6}$/;
const LOGO = /^data:image\/(png|jpeg|jpg|webp|svg\+xml);base64,[A-Za-z0-9+/=]+$/;

const sectionSchema = z.object({
  id: z.enum(REPORT_SECTION_IDS),
  enabled: z.boolean(),
});

export const reportTemplateSchema = z.object({
  branding: z.object({
    logoDataUrl: z
      .string()
      .max(MAX_LOGO_DATA_URL_LENGTH, "Logo is too large (max ~200 KB)")
      .regex(LOGO, "Logo must be a PNG, JPEG, WebP or SVG image")
      .nullable(),
    headerText: z.string().max(120),
    subheaderText: z.string().max(200),
    footerText: z.string().max(200),
    accentColor: z.string().regex(HEX, "Accent colour must be #RRGGBB"),
  }),
  sections: z
    .array(sectionSchema)
    .length(REPORT_SECTION_IDS.length)
    .refine((s) => new Set(s.map((x) => x.id)).size === s.length, "Each section must appear once"),
  format: z.object({
    pageSize: z.enum(["a4", "letter"]),
    orientation: z.enum(["portrait", "landscape"]),
    style: z.enum(["modern", "classic", "compact"]),
    fontSize: z.number().int().min(9).max(16),
  }),
});
export type ReportTemplate = z.infer<typeof reportTemplateSchema>;

export const DEFAULT_REPORT_TEMPLATE: ReportTemplate = {
  branding: {
    logoDataUrl: null,
    headerText: "",
    subheaderText: "",
    footerText: "Confidential — generated by ResilienceSoft Interview",
    accentColor: "#6d28d9",
  },
  sections: REPORT_SECTION_IDS.map((id) => ({
    id,
    enabled: id !== "transcript" && id !== "errorLog",
  })),
  format: { pageSize: "a4", orientation: "portrait", style: "modern", fontSize: 11 },
};

/**
 * Lenient parse of a stored template: unknown/invalid fields fall back to defaults,
 * sections are de-duplicated and any missing section is appended (disabled).
 * Never throws — old or partial rows always yield a usable template.
 */
export function normalizeReportTemplate(raw: unknown): ReportTemplate {
  const d = DEFAULT_REPORT_TEMPLATE;
  const r = (raw && typeof raw === "object" ? raw : {}) as Record<string, any>;
  const pick = <T>(schema: z.ZodType<T>, v: unknown, fallback: T): T => {
    const p = schema.safeParse(v);
    return p.success ? p.data : fallback;
  };
  const b = (r.branding ?? {}) as Record<string, unknown>;
  const f = (r.format ?? {}) as Record<string, unknown>;
  const bs = reportTemplateSchema.shape.branding.shape;
  const fs = reportTemplateSchema.shape.format.shape;

  const seen = new Set<string>();
  const sections: ReportTemplate["sections"] = [];
  for (const s of Array.isArray(r.sections) ? r.sections : []) {
    const p = sectionSchema.safeParse(s);
    if (p.success && !seen.has(p.data.id)) {
      seen.add(p.data.id);
      sections.push(p.data);
    }
  }
  for (const id of REPORT_SECTION_IDS) if (!seen.has(id)) sections.push({ id, enabled: false });
  // Brand-new template (no stored sections) → use default enabled flags.
  const useDefaultSections = !Array.isArray(r.sections) || r.sections.length === 0;

  return {
    branding: {
      logoDataUrl: pick(bs.logoDataUrl, b.logoDataUrl, d.branding.logoDataUrl),
      headerText: pick(bs.headerText, b.headerText, d.branding.headerText),
      subheaderText: pick(bs.subheaderText, b.subheaderText, d.branding.subheaderText),
      footerText: pick(bs.footerText, b.footerText, d.branding.footerText),
      accentColor: pick(bs.accentColor, b.accentColor, d.branding.accentColor),
    },
    sections: useDefaultSections ? d.sections.map((s) => ({ ...s })) : sections,
    format: {
      pageSize: pick(fs.pageSize, f.pageSize, d.format.pageSize),
      orientation: pick(fs.orientation, f.orientation, d.format.orientation),
      style: pick(fs.style, f.style, d.format.style),
      fontSize: pick(fs.fontSize, f.fontSize, d.format.fontSize),
    },
  };
}

/** Move a section up (-1) or down (+1); out-of-range moves are no-ops. */
export function moveSection(
  sections: ReportTemplate["sections"],
  index: number,
  delta: number,
): ReportTemplate["sections"] {
  const to = index + delta;
  if (index < 0 || index >= sections.length || to < 0 || to >= sections.length) return sections;
  const next = [...sections];
  const [item] = next.splice(index, 1);
  next.splice(to, 0, item);
  return next;
}

/** Page size in mm for jsPDF given format settings. */
export function pageSizeMm(format: ReportTemplate["format"]): { width: number; height: number } {
  const base = format.pageSize === "letter" ? { width: 215.9, height: 279.4 } : { width: 210, height: 297 };
  return format.orientation === "landscape" ? { width: base.height, height: base.width } : base;
}

/**
 * Split a tall rendered report into page slices, preferring to cut at block
 * boundaries (so cards/questions are not sliced in half). A boundary is only
 * used if it keeps at least 30% of the page filled; otherwise we hard-cut.
 * Returns [start, end) pairs in the same units as the inputs.
 */
export function computePageBreaks(
  totalHeight: number,
  pageHeight: number,
  boundaries: number[],
): [number, number][] {
  if (totalHeight <= 0 || pageHeight <= 0) return [];
  const sorted = Array.from(new Set(boundaries.map((b) => Math.round(b)))).sort((a, b) => a - b);
  const out: [number, number][] = [];
  let start = 0;
  while (start < totalHeight - 0.5) {
    const limit = start + pageHeight;
    let end = Math.min(limit, totalHeight);
    if (limit < totalHeight) {
      const candidates = sorted.filter((b) => b > start + pageHeight * 0.3 && b <= limit);
      if (candidates.length) end = candidates[candidates.length - 1];
    }
    out.push([start, end]);
    start = end;
  }
  return out;
}
